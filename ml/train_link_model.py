"""
RESILINK GRID v4 — RF Link-State TinyML Classifier (Robust Scaled)
Classifies link telemetry (RSSI, PDR, retries, RTT, queue depth, jitter) into:
  0: HEALTHY
  1: DEGRADING
  2: CRITICAL
Exports link_model_data.h with INT8 quantized parameters.
"""

import os
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import confusion_matrix, accuracy_score
from data_generator import generate_rf_link_dataset


LINK_FEATURES = ["rssi", "pdr", "retries", "rtt", "queue_depth", "jitter"]
LINK_CLASSES = ["HEALTHY", "DEGRADING", "CRITICAL"]


def train_and_evaluate_link_model():
    print("=================================================================")
    print("RESILINK GRID v4 — Training TinyML RF Link-State Classifier")
    print("=================================================================")

    df = generate_rf_link_dataset(num_samples=6000, seed=123)
    X = df[LINK_FEATURES].values
    y = df["link_class"].values

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.25, random_state=123, stratify=y
    )

    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_test_scaled = scaler.transform(X_test)

    means = scaler.mean_
    stds = scaler.scale_

    # Compact MLP: 6 Inputs -> Dense(12, ReLU) -> Dense(3, Softmax)
    model = MLPClassifier(
        hidden_layer_sizes=(12,),
        activation="relu",
        solver="adam",
        max_iter=300,
        random_state=123,
        learning_rate_init=0.01
    )
    model.fit(X_train_scaled, y_train)

    y_pred = model.predict(X_test_scaled)
    acc = accuracy_score(y_test, y_pred)
    cm = confusion_matrix(y_test, y_pred)

    print(f"Overall Link Classification Accuracy: {acc * 100:.2f}%\n")
    print("--- Link Confusion Matrix ---")
    print(f"{'':>12} {'Pred HEALTHY':>14} {'Pred DEGRADE':>14} {'Pred CRIT':>14}")
    for i, row in enumerate(cm):
        print(f"{'True ' + LINK_CLASSES[i]:>12} {row[0]:>14} {row[1]:>14} {row[2]:>14}")

    # INT8 Quantization
    quantized_weights = []
    weight_scales = []
    for idx, (W, b) in enumerate(zip(model.coefs_, model.intercepts_)):
        max_val = max(np.max(np.abs(W)), np.max(np.abs(b)))
        scale = max_val / 127.0 if max_val > 0 else 1.0
        W_int8 = np.clip(np.round(W / scale), -128, 127).astype(np.int8)
        b_int32 = np.round(b / scale).astype(np.int32)
        quantized_weights.append((W_int8, b_int32))
        weight_scales.append(scale)

    output_dir = os.path.dirname(os.path.abspath(__file__))
    header_path = os.path.join(output_dir, "link_model_data.h")
    firmware_header_path = os.path.join(output_dir, "..", "firmware", "mcxn236", "include", "link_model_data.h")

    write_link_c_header(header_path, means, stds, quantized_weights, weight_scales)
    write_link_c_header(firmware_header_path, means, stds, quantized_weights, weight_scales)

    print(f"Exported Link-State C headers to {header_path} and {firmware_header_path}")
    return acc


def write_link_c_header(filepath, means, stds, quantized_weights, scales):
    os.makedirs(os.path.dirname(filepath), exist_ok=True)
    with open(filepath, "w") as f:
        f.write("/*\n")
        f.write(" * RESILINK GRID v4 — Autogenerated TinyML RF Link-State Classifier (INT8)\n")
        f.write(" * Target: NXP FRDM-MCXN236 (Cortex-M33 @ 150MHz)\n")
        f.write(" */\n\n")
        f.write("#ifndef LINK_MODEL_DATA_H\n")
        f.write("#define LINK_MODEL_DATA_H\n\n")
        f.write("#include <stdint.h>\n")
        f.write("#include <stdbool.h>\n\n")

        f.write("#define LINK_MODEL_NUM_INPUTS   6\n")
        f.write("#define LINK_MODEL_NUM_CLASSES  3\n")
        f.write("#define LINK_MODEL_L1_NODES     12\n\n")

        f.write("static const float LINK_FEATURE_MEANS[6] = {\n    ")
        f.write(", ".join([f"{v:.4f}f" for v in means]))
        f.write("\n};\n\n")

        f.write("static const float LINK_FEATURE_STDS[6] = {\n    ")
        f.write(", ".join([f"{v:.4f}f" for v in stds]))
        f.write("\n};\n\n")

        # Layer 1
        W1, b1 = quantized_weights[0]
        f.write(f"static const float LINK_SCALE_L1 = {scales[0]:.8f}f;\n")
        f.write("static const int8_t LINK_WEIGHTS_L1[6][12] = {\n")
        for r in range(6):
            f.write("    {" + ", ".join([f"{W1[r, c]}" for c in range(12)]) + "},\n")
        f.write("};\n\n")
        f.write("static const int32_t LINK_BIAS_L1[12] = {\n    ")
        f.write(", ".join([f"{b1[c]}" for c in range(12)]))
        f.write("\n};\n\n")

        # Output Layer
        W2, b2 = quantized_weights[1]
        f.write(f"static const float LINK_SCALE_OUT = {scales[1]:.8f}f;\n")
        f.write("static const int8_t LINK_WEIGHTS_OUT[12][3] = {\n")
        for r in range(12):
            f.write("    {" + ", ".join([f"{W2[r, c]}" for c in range(3)]) + "},\n")
        f.write("};\n\n")
        f.write("static const int32_t LINK_BIAS_OUT[3] = {\n    ")
        f.write(", ".join([f"{b2[c]}" for c in range(3)]))
        f.write("\n};\n\n")

        f.write("#endif /* LINK_MODEL_DATA_H */\n")


if __name__ == "__main__":
    train_and_evaluate_link_model()
